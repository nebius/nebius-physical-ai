def test_the_shape_instrument_tells_a_lump_from_a_rind(harness):
    """The interpretive claim is a thickness claim, so test thickness directly.

    Eight cells as a 2x2x2 lump and eight cells as a 1x2x4 sheet are the two
    readings the record distinguishes. Both are structured by size; only the
    thickness separates them, and that is the number the verdict leans on.
    """
    numpy = pytest.importorskip("numpy")

    lump = numpy.zeros((6, 6, 6), dtype=bool)
    lump[1:3, 1:3, 1:3] = True
    rind = numpy.zeros((6, 6, 6), dtype=bool)
    rind[1, 1:3, 1:5] = True

    lump_report = harness.classify(lump)
    rind_report = harness.classify(rind)

    assert lump_report["largest_component_cells"] == 8
    assert rind_report["largest_component_cells"] == 8
    assert lump_report["is_structured"] is True
    assert rind_report["is_structured"] is True
    assert lump_report["largest_component_min_thickness_cells"] == 2
    assert rind_report["largest_component_min_thickness_cells"] == 1
    assert sorted(lump_report["largest_component_extent_cells"]) == [2, 2, 2]
    assert sorted(rind_report["largest_component_extent_cells"]) == [1, 2, 4]
