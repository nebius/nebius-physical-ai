"""Run the product's own reconstruct stage and record the crop margin it now reports.

Not a mirror of the stage: this calls `run_multiway` and `run_reconstruct`, the same two
entry points the workflow calls, and reads `crop_margin` out of the returned summary. The
point is that the figure is available to a caller rather than computable in principle.

Two support factors, because the margin is a property of where the cut lands relative to
this scan's geometry, and a reader should see it move with the parameter rather than
take one number on trust.
"""

from __future__ import annotations

import datetime
import hashlib
import json
import sys
import tempfile
from pathlib import Path

FACTORS = (1.0, 0.87, 0.0)
VOXEL = 0.05


def _fragment(index: int, path: str) -> dict:
    payload = Path(path).read_bytes()
    return {
        "id": f"f{index}",
        "uri": path,
        "sha256": hashlib.sha256(payload).hexdigest(),
        "bytes": len(payload),
    }


#: Where the stage lives inside the repository. The absolute path a run records is
#: this author's checkout and does not exist anywhere else, so the identity that
#: travels is this plus the source hash below.
RUNNER_RELATIVE = "npa/src/npa/workbench/open3d/runner.py"


def _runner_origin() -> dict[str, str]:
    """Which copy of the product code produced the figures below.

    These worktrees borrow an interpreter from a sibling checkout, so the binding that
    matters is not the executable but where `npa` was imported from. A record that
    names a relative `npa/.venv/bin/python` cannot be re-run: that path does not exist
    here.

    The absolute path is kept because it is what actually happened, and it is paired
    with the repository-relative path and the imported file's hash. Only the latter two
    can be checked on another machine -- a reader on a CI runner can confirm the record
    was produced from this revision of the stage, which the absolute path cannot tell
    them.
    """

    from npa.workbench.open3d import runner

    source = Path(runner.__file__).resolve()
    return {
        "absolute_path_on_the_machine_that_ran_it": str(source),
        "repository_relative": RUNNER_RELATIVE,
        "sha256": hashlib.sha256(source.read_bytes()).hexdigest(),
    }


def _open3d_origin() -> dict[str, str]:
    """Both the path imported and the path it resolves to.

    They differ here: the borrowed virtualenv's `open3d` is a symlink into a third
    worktree's site-packages. Recording only the resolved path hides which environment
    was actually invoked, and recording only the import path hides which bytes ran.
    """

    import open3d

    imported = Path(open3d.__file__)
    return {
        "imported_from": str(imported),
        "resolves_to": str(imported.resolve()),
        "version": open3d.__version__,
    }


def _what_the_result_shows(observed: dict) -> str:
    """Read off the rows above rather than restated from an earlier run.

    The sentence this replaces said "a handful of vertices ... at both enabled factors"
    and the next run returned zero at one of them. A narrative kept by hand next to
    figures regenerated by machine drifts on the first rerun, which is the failure this
    harness is supposed to be evidence against.
    """

    parts = []
    for name, got in sorted(observed.items()):
        margin = got["crop_margin"]
        if not margin["applies"]:
            parts.append(f"{name}: no threshold, so no margin ({margin['why_not']})")
            continue
        comparison = margin["reference_comparison"]
        parts.append(
            f"{name}: closest vertex "
            f"{margin['closest_vertex_to_the_threshold']:.3g} from a "
            f"{margin['threshold']:.3g} threshold "
            f"({margin['closest_as_a_fraction_of_the_threshold'] * 100:.3g}% of it), "
            f"{comparison['vertices_closer_than_the_routine_reference']} vertices "
            "closer than the routine reference and "
            f"{comparison['vertices_closer_than_the_larger_reference']} closer than "
            f"the larger, out of {got['unsupported_vertices_removed']} removed"
        )
    return (
        "Measured on this run: "
        + "; ".join(parts)
        + ". These are counts for this run against two reference figures, nothing "
        "more. The references are sample maxima from one scene, and a rerun "
        "regenerates the vertex set rather than perturbing it, so neither these "
        "counts nor the 46 pair comparisons behind the references add up to a "
        "prediction about what a rerun would decide."
    )


def main() -> int:
    import open3d as o3d
    from npa.workbench.open3d.runner import (
        POISSON_VERTEX_DISPLACEMENT_BOUND_M,
        POISSON_VERTEX_DISPLACEMENT_ROUTINE_M,
        run_multiway,
        run_reconstruct,
    )

    data = o3d.data.DemoICPPointClouds()
    observed = {}

    with tempfile.TemporaryDirectory() as scratch:
        root = Path(scratch)
        registration = root / "registration"
        registration.mkdir()
        run_multiway(
            {
                "manifest": {
                    "fragments": [
                        _fragment(index, path) for index, path in enumerate(data.paths)
                    ],
                    "voxel_size": VOXEL,
                },
                "fragments": {
                    f"f{index}": path for index, path in enumerate(data.paths)
                },
            },
            registration,
            "crop-margin-live",
        )
        fused = next(registration.rglob("fused.ply"))

        for factor in FACTORS:
            output = root / f"reconstruct-{factor}"
            output.mkdir()
            summary = run_reconstruct(
                {
                    "request": {
                        "input_path": str(fused),
                        "output_path": str(output),
                        "run_id": f"crop-margin-live-{factor}",
                        "poisson_depth": 9,
                        "density_quantile": 0.02,
                        "support_distance_factor": factor,
                    },
                    "fused_path": str(fused),
                    "voxel_size": VOXEL,
                },
                output,
                f"crop-margin-live-{factor}",
            )
            observed[f"support_distance_factor_{factor}"] = {
                "unsupported_vertices_removed": summary["unsupported_vertices_removed"],
                "crop_margin": summary["crop_margin"],
            }

    record = {
        "what_this_measures": (
            "That the support crop's decision margin is reported by the product's own "
            "reconstruct stage, and what it says on the record's own input. The figure "
            "existed inside the crop before this and was discarded, so a user had no "
            "way to see how close the crop came to deciding something else."
        ),
        "why_it_matters": (
            "The crop is a threshold on a per-vertex distance, so how close the "
            "geometry sits to that cut is a fact about the caller's scan rather than a "
            "property of the rule. It is the quantity a caller can act on: a denser "
            "capture shortens the distances themselves."
        ),
        "executed": (
            "npa.workbench.open3d.runner.run_multiway then run_reconstruct, the entry "
            "points the workflow calls; no mirrored copy of the stage"
        ),
        "input": "open3d.data DemoICPPointClouds, three fragments, voxel 0.05",
        "reference_displacements_the_comparison_uses": {
            "routine_m": POISSON_VERTEX_DISPLACEMENT_ROUTINE_M,
            "largest_recorded_m": POISSON_VERTEX_DISPLACEMENT_BOUND_M,
            "measured_at": (
                "one scene at voxel 0.02 or 0.05, Poisson depth 9. This run is at "
                "voxel 0.05 and depth 9, so the comparison's own "
                "configuration_measured flag is true here -- which is a statement "
                "about the settings matching, not about this scene being that scene."
            ),
        },
        "per_support_factor": observed,
        "what_the_result_shows": _what_the_result_shows(observed),
        "what_this_does_not_establish": (
            "Anything about whether the reconstruction is correct -- a vertex far from "
            "the cut can still be in the wrong place. Nor what a rerun would decide. "
            "An earlier version of this field classified runs as reproducible in "
            "practice and offered the near-threshold counts as an error bar for future "
            "counts; both were removed, because a rerun has no vertex correspondence "
            "for either claim to be about."
        ),
        "how_to_reproduce": {
            "command": (
                "python docs/evidence/open3d/harness/crop_margin_live.py  # with this "
                "repository's npa/src on PYTHONPATH"
            ),
            "interpreter_note": (
                "These worktrees have no npa/.venv of their own; the run below records "
                "the interpreter that was actually used and where npa and open3d were "
                "imported from."
            ),
            "note": (
                "Registration and reconstruction are both nondeterministic, so the "
                "counts move between runs. The orders of magnitude are what reproduce; "
                "the exact counts are this run's."
            ),
        },
        "provenance": {
            "harness": "harness/crop_margin_live.py",
            "harness_sha256": "recomputed below",
            "path_is_relative_to": "this evidence directory",
            "interpreter": sys.executable,
            "python": sys.version.split()[0],
            "npa_runner_imported_from": _runner_origin(),
            "what_can_be_rechecked_elsewhere": (
                "npa_runner_imported_from.repository_relative and .sha256. The "
                "absolute path is this machine's and is recorded as history, not as "
                "something another checkout can verify."
            ),
            "open3d_imported_from": _open3d_origin(),
            "utc": datetime.datetime.now(datetime.UTC).isoformat(),
        },
    }
    record["provenance"]["harness_sha256"] = hashlib.sha256(
        Path(__file__).read_bytes()
    ).hexdigest()
    json.dump(record, sys.stdout, indent=2)
    sys.stdout.write("\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
